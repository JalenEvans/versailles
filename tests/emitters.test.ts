/**
 * Parses every fixture expr with the real parser so the context carries real
 * ASTs in parsedContracts (the shape the loader produces, build-spec §6).
 * Throws only on a fixture-authoring error — never a generator behaviour.
 */
function parseAll(contracts: ContractsFile): Record<string, Node> {
	const parsed: Record<string, Node> = {};
	const walk = (clauses: ContractClause[], kind: ClauseKind): void => {
		for (const clause of clauses) {
			const result = parseExpression(clause.expr, kind, clause.id);
			if (!result.ok) {
				throw new Error(
					`fixture parse failed for ${clause.id}: ${JSON.stringify(result.errors)}`,
				);
			}
			parsed[clause.id] = result.ast;
		}
	};
	for (const component of Object.values(contracts.contracts)) {
		walk(component.invariants ?? [], "invariants");
		for (const operation of Object.values(component.operations ?? {})) {
			walk(operation.preconditions ?? [], "preconditions");
			walk(operation.postconditions ?? [], "postconditions");
		}
	}
	return parsed;
}

/**
 * Builds a fully-loaded, isValid VersaillesContext in memory (no files, no
 * loader), mirroring the fixture approach in tests/generator.test.ts. With no
 * rejection argument the config carries NO rejection block — the ADR-0007
 * default (throws).
 */
function makeContext(rejectionIdiom?: "throws" | "returns"): VersaillesContext {
	const contracts = contractsFixture();
	return {
		config: makeConfig(rejectionIdiom),
		contracts,
		manifests: manifestsFixture(),
		predicates: predicatesFixture(),
		parsedContracts: parseAll(contracts),
		parseErrors: [],
		validationErrors: [],
		validationWarnings: [],
		isValid: true,
	};
}

function allCases(suite: PlannedSuite): PlannedCaseLike[] {
	return [
		...suite.operations.flatMap((group) => group.cases),
		...suite.invariantCases,
	];
}

/** Minimal structural subset of PlannedCase used by the helpers below. */
type PlannedCaseLike = {
	id: string;
	inputs: Record<string, unknown>;
	expects: { outcome: "accept" | "reject"; rejectionIdiom?: string };
};

function rejectCases(suite: PlannedSuite): PlannedCaseLike[] {
	return allCases(suite).filter((case_) => case_.expects.outcome === "reject");
}

describe("emitSuite — xunit emitter (§9.4, ADR-0008/0009)", () => {
	it("renders per-component *.Tests.cs files with a test class per component and a namespace import", () => {
		const suite = planTestCases(makeContext());
		const files = emitSuite(suite, "xunit" as never);

		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		const customer = files.find((file) =>
			file.path.endsWith("CustomerService.Tests.cs"),
		);
		expect(account).toBeDefined();
		expect(customer).toBeDefined();
		expect(account?.path.startsWith(".versailles/generated/")).toBe(true);

		// Class per component, mirroring vitest's per-component files.
		expect(account?.content).toContain("public class AccountServiceTests");
		expect(customer?.content).toContain("public class CustomerServiceTests");

		// A valid xUnit C# file: using directives + [Fact] attributes.
		expect(account?.content).toContain("using System;");
		expect(account?.content).toContain("using Xunit;");
		expect(account?.content).toContain(
			"using Versailles.Components.AccountService;",
		);
		expect(account?.content).toContain("[Fact]");

		// Violation/precondition/postcondition + invariant cases render [Fact].
		expect(account?.content).toContain("Assert.Throws<Exception>(");
		expect(account?.content).toContain(
			"public void AccountService_withdraw_invariant_0()",
		);

		// Traceability comment per file (§9.3).
		expect(account?.content).toContain("// traces:");
		expect(
			account?.content
				.split("\n")
				.some((line) =>
					/AccountService\.(inv0|withdraw\.|setStatus\.)/.test(line),
				),
		).toBe(true);
	});

	it("renders [Fact] + Assert.Throws<Exception> for reject cases — throws idiom from the case (ADR-0007)", () => {
		const suite = planTestCases(makeContext());
		const files = emitSuite(suite, "xunit" as never);
		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		expect(account).toBeDefined();

		// Boundary reject (amount=9 falsifies amount >= 10).
		expect(account?.content).toContain(
			"Assert.Throws<Exception>(() => AccountService.withdraw(new { amount = 9 }));",
		);
		// Boundary reject (amount=101 falsifies amount <= 100).
		expect(account?.content).toContain(
			"Assert.Throws<Exception>(() => AccountService.withdraw(new { amount = 101 }));",
		);
		// Expected-rejection: postconditions hold, invariant violated.
		expect(account?.content).toContain(
			"Assert.Throws<Exception>(() => AccountService.withdraw(new { amount = 51, balance = 50 }));",
		);
		// Accept cases are NOT wrapped in Assert.Throws.
		expect(account?.content).not.toContain(
			"Assert.Throws<Exception>(() => AccountService.withdraw(new { amount = 10 }));",
		);
	});

	it("renders [Theory] + [InlineData] for equivalence-partition cases", () => {
		const suite = planTestCases(makeContext());
		const files = emitSuite(suite, "xunit" as never);
		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		expect(account).toBeDefined();

		expect(account?.content).toContain("[Theory]");
		expect(account?.content).toContain('[InlineData("ACTIVE")]');
		expect(account?.content).toContain('[InlineData("FROZEN")]');
		// The outside-set partition value renders as its own InlineData row.
		expect(account?.content).toContain('[InlineData("INVALID")]');
		// Theory methods declare the input keys as parameters.
		expect(account?.content).toContain(
			"public void AccountService_setStatus_partition_0(string newStatus)",
		);
		// The reject partition case keeps the throws idiom inside the body.
		expect(account?.content).toContain(
			"Assert.Throws<Exception>(() => AccountService.setStatus(new { newStatus }));",
		);
	});

	it("calls the component operation with the configured inputs in operation scope", () => {
		const suite = planTestCases(makeContext());
		const files = emitSuite(suite, "xunit" as never);
		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		expect(account).toBeDefined();

		// Boundary accept case calls the component method with the input value.
		expect(account?.content).toContain(
			"var result = AccountService.withdraw(new { amount = 10 });",
		);
		// Postcondition case passes captured pre-state alongside params
		// (mirrors vitest's single object literal).
		expect(account?.content).toContain(
			"var result = AccountService.withdraw(new { amount = 55, balance = 50 });",
		);
		// The method name derives from the case id — never the case-id tail as
		// a method (Center B1 mirror).
		expect(account?.content).not.toContain("withdraw.boundary-0(");
	});

	it("renders Assert.Null for the returns rejection idiom when configured (ADR-0007)", () => {
		const suite = planTestCases(makeContext("returns"));
		const files = emitSuite(suite, "xunit" as never);
		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		expect(account).toBeDefined();
		const rejectCase = rejectCases(suite).find(
			(case_) => case_.inputs.amount === 9,
		);
		expect(rejectCase).toBeDefined();
		expect(rejectCase?.expects.rejectionIdiom).toBe("returns");
		expect(account?.content).toContain(
			"Assert.Null(AccountService.withdraw(new { amount = 9 }));",
		);
		expect(account?.content).not.toContain("Assert.Throws<Exception>(");
	});

	it("renders real invariant assertions on the subject field — not just Assert.NotNull (Center W2)", () => {
		const suite = planTestCases(makeContext());
		const files = emitSuite(suite, "xunit" as never);
		const account = files.find((file) =>
			file.path.endsWith("AccountService.Tests.cs"),
		);
		expect(account).toBeDefined();
		const inv = suite.invariantCases.find(
			(case_) => case_.kind === "invariant",
		);
		expect(inv).toBeDefined();

		// Scope to the invariant case's own rendered method block.
		const start = account?.content.indexOf(
			"public void AccountService_withdraw_invariant_0()",
		);
		expect(start).toBeGreaterThan(-1);
		const end = account?.content.indexOf("\n\n", start);
		const block = account?.content.slice(start, end);

		// The invariant's subject field (balance) is asserted with a real
		// matcher — the degenerate bare-accept render alone would fail this.
		expect(block).toContain("Assert.NotNull(result)");
		expect(block).toContain("Assert.True(result.balance >= 0)");
	});
});

