/**
 * xUnit and pytest emitters (ADR-0008/0009, build-spec §9.4) — regression
 * battery for the complete v1 emitter matrix.
 *
 * emitSuite(suite, framework) dispatches across vitest | xunit | pytest
 * (src/generator/index.ts, ADR-0009). ADR-0009 pins the v1 matrix C#→xUnit
 * (`*.Tests.cs`) and Python→pytest (`test_*.py`); config.schema.json accepts
 * `testFramework: "xunit" | "pytest"` and src/cli/handlers/generate.ts routes
 * `context.config.testFramework` straight into emitSuite. This file freezes
 * the emitters' fixed behavior so regressions fail here. The suite IR is
 * shared and framework-agnostic (ADR-0008); only the rendering differs. The
 * vitest emitter (src/generator/emitters/vitest.ts) is the template — every
 * decision below mirrors its existing semantics.
 *
 * ── Fixed-behavior contract (what the xunit/pytest emitters MUST render) ───
 *
 * File shapes (per component, mirroring vitest's per-component files):
 *   xunit:  <generatedDir>/<Component>.Tests.cs
 *   pytest: <generatedDir>/test_<Component>.py
 *
 * Header (deterministic, no timestamps — ADR-0002):
 *   xunit:  `// Auto-generated by the Versailles deterministic generator core.`
 *           `// Do not edit — regenerate with \`versailles generate\`.`
 *           `// traces: "ClauseId", "ClauseId", ...`   (clause ids
 *           JSON.stringify-escaped and joined with ", " — §9.3)
 *   pytest: same three lines with `#` comment markers.
 *
 * Imports (the modulePaths analog — Center W4; mirrors vitest's
 * `modulePaths[component] ?? "../../src/<Component>.js"`):
 *   xunit:  `using System;` + `using Xunit;` +
 *           `using <modulePaths[component] ?? "Versailles.Components.<Component>">;`
 *   pytest: `import pytest` +
 *           `from <modulePaths[component] ?? "components.<Component>"> import <Component>`
 *
 * Naming:
 *   xunit class: `public class <Component>Tests`
 *   method name: the FULL case id with every non [A-Za-z0-9_] char replaced
 *                by `_` (e.g. `AccountService.withdraw.boundary-0` →
 *                `public void AccountService_withdraw_boundary_0()`), so names
 *                are unique per file and never collide.
 *   pytest fn:   `def test_<id with non [A-Za-z0-9_] → _>():`
 *   case comment above each method: `// <case.id> — <case.description>`
 *                (xunit) / `# <case.id> — <case.description>` (pytest).
 *
 * Case rendering (per case, never hardcoded — ADR-0007):
 *   reject + "throws":
 *     xunit:  `Assert.Throws<Exception>(() => <Component>.<operation>(<args>));`
 *     pytest: `with pytest.raises(Exception):` / `    <Component>.<operation>(<args>)`
 *   reject + "returns":
 *     xunit:  `Assert.Null(<Component>.<operation>(<args>));`
 *     pytest: `assert <Component>.<operation>(<args>) is None`
 *   accept (no assertions):
 *     xunit:  `var result = <Component>.<operation>(<args>);` + `Assert.NotNull(result);`
 *     pytest: `result = <Component>.<operation>(<args>)` + `assert result is not None`
 *   accept (with assertions — Center W2, mirror vitest's MATCHER map):
 *     xunit:  Assert.NotNull(result) + per AssertionDescriptor:
 *             >= → `Assert.True(result.<subject> >= <literal>)`
 *             >  → `Assert.True(result.<subject> > <literal>)`
 *             <= → `Assert.True(result.<subject> <= <literal>)`
 *             <  → `Assert.True(result.<subject> < <literal>)`
 *             == → `Assert.Equal(<literal>, result.<subject>)`
 *             != → `Assert.NotEqual(<literal>, result.<subject>)`
 *     pytest: `assert result is not None` + `assert result.<subject> <op> <literal>`
 *   <args> is a single object mirroring vitest's object literal — ALL case
 *   inputs (params + captured pre-state fields) in Object.entries order:
 *     xunit:  `new { amount = 9 }`, `new { amount = 55, balance = 50 }`
 *     pytest: `{"amount": 9}`, `{"amount": 55, "balance": 50}` (null → `None`)
 *   Partition cases ([Theory]/[InlineData], parametrize):
 *     xunit:  `[Theory]` + `[InlineData(<value>)]` per case; method declares
 *             the input keys as parameters (e.g. `(string newStatus)`); the
 *             body builds the object from the named params (`new { newStatus }`).
 *     pytest: `@pytest.mark.parametrize("<key>", [<value>])` per case;
 *             `def test_...( <key> )`; body builds the dict
 *             (`{"newStatus": newStatus}`).
 *
 * Dispatch (src/generator/index.ts + ir.ts):
 *   - emitSuite(suite, "xunit" | "pytest", options) dispatches instead of
 *     throwing; EmitterFramework widens to "vitest" | "xunit" | "pytest".
 *   - An UNKNOWN framework string still throws at the seam (the ADR-0008/0009
 *     rejection policy — config.schema.json rejects non-matrix values too).
 *   - Identifier safety (Center W1): component/operation names flow into
 *     class/function/file names and calls — the emitters must refuse
 *     non-identifier names (mirror vitest's assertIdentifier), never emitting
 *     a breakout file.
 *   - Determinism (ADR-0002): same suite in → byte-identical content out.
 */

